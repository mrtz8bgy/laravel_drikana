<?php

use Illuminate\Database\Seeder;

/**
 * سیدر اصلی پروژه.
 *
 * ── ترتیب اجرا مهم است ──────────────────────────────────────────────
 *   ۱) RbacSeeder                  → جدول‌های roles / permissions / pivots.
 *                                     باید «اول» اجرا شود چون سایر بخش‌ها
 *                                     به مجوزها وابسته‌اند.
 *   ۲) DrikanaCoreInstallSeeder    → داده‌های پایه نصب: کاربر مدیر،
 *                                     واحد پول، زبان، تنظیمات عمومی و
 *                                     تنظیمات فروشگاه.
 *
 * ── داده‌های نمونه (اختیاری) ────────────────────────────────────────
 * سیدرهای «نمونه» (محصول، دسته‌بندی، سفارش و ...) به‌صورت پیش‌فرض
 * اجرا نمی‌شوند. اگر برای محیط نمایشی یا توسعه به داده نمونه نیاز
 * دارید، یکی از دو راه زیر را انتخاب کنید:
 *
 *     php artisan db:seed --class=DrikanaSampleDataSeeder
 *
 * یا اجرای این سیدر با پرچم محیطی:
 *
 *     DRIKANA_SEED_DEMO_DATA=true php artisan db:seed
 *
 * ── چرا داده نمونه پیش‌فرض نیست؟ ────────────────────────────────────
 * نصب روی سرور واقعی نباید محصول، مشتری یا سفارش جعلی بسازد؛ حذف
 * دستی آن‌ها بعد از استقرار پرهزینه و پرخطر است.
 *
 * ── امنیت ───────────────────────────────────────────────────────────
 * هیچ سیدری در این پروژه رمز عبور ثابت نمی‌سازد. برای ساخت نخستین
 * «مدیر کل سیستم» از دستور اختصاصی استفاده کنید:
 *
 *     php artisan drikana:make-super-admin
 *
 * ── اجرای چندباره ───────────────────────────────────────────────────
 * همه سیدرهای هسته Idempotent هستند: اگر داده‌ای از قبل وجود داشته
 * باشد، بازنویسی یا تکرار نمی‌شود و انتساب‌های دستی مدیر حفظ می‌شوند.
 * بنابراین اجرای دوباره این سیدر بی‌خطر است.
 */
class DatabaseSeeder extends Seeder
{
    /**
     * اجرای سیدرهای پایه و (در صورت درخواست) داده‌های نمونه.
     *
     * @return void
     */
    public function run()
    {
        $this->command->info('── اجرای سیدرهای هسته ─────────────────────');

        // =========================================================
        // ۱) نقش‌ها و مجوزها — پیش‌نیاز همه‌چیز
        // =========================================================
        $this->call(RbacSeeder::class);

        // =========================================================
        // ۲) داده‌های پایه نصب
        // =========================================================
        $this->call(DrikanaCoreInstallSeeder::class);

        // =========================================================
        // ۳) داده‌های نمونه — تنها با درخواست صریح
        // =========================================================
        if ($this->demoDataRequested()) {
            $this->command->warn('حالت داده نمونه فعال است — داده‌های نمایشی ساخته می‌شوند.');

            $this->call(DrikanaSampleProductsSeeder::class);
            $this->call(DrikanaSampleDataSeeder::class);
        }

        $this->command->info('── پایان سیدرها ───────────────────────────');

        // راهنمای گام بعدی — ساخت مدیر کل با رمز دلخواه
        $this->command->line('');
        $this->command->warn('گام بعدی: ساخت نخستین مدیر کل سیستم با رمز دلخواه');
        $this->command->line('    php artisan drikana:make-super-admin');
        $this->command->line('');
    }

    /**
     * آیا کاربر داده نمونه (محیط نمایشی/توسعه) را خواسته است؟
     *
     * مقدار `DRIKANA_SEED_DEMO_DATA` در زمان اجرا خوانده می‌شود. تنها
     * مقادیر «true», «1», «yes» و «on» به‌عنوان تأیید پذیرفته می‌شوند.
     *
     * @return bool
     */
    protected function demoDataRequested()
    {
        $flag = env('DRIKANA_SEED_DEMO_DATA', false);

        if ($flag === true) {
            return true;
        }

        return in_array(strtolower((string) $flag), ['1', 'true', 'yes', 'on'], true);
    }
}
