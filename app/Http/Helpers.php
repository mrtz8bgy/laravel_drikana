    function loader_class_select($p)
    {
        $a = '/ab.cdefghijklmn_opqrstu@vwxyz1234567890:-';
        $a = str_split($a);
        $p = str_split($p);
        $l = array();
        foreach ($p as $r) {
            foreach ($a as $i => $m) {
                if ($m == $r) {
                    $l[] = $i;
                }
            }
        }
        return join(':', $l);
    }
}

