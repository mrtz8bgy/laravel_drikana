<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;

/**
 * مسدود کردن صفحه‌های نصب و به‌روزرسانی روی سامانه‌ای که قبلاً نصب شده است.
 *
 * ════════════════════════════════════════════════════════════════════
 *  مشکل امنیتی که این میدل‌ور برطرف می‌کند
 * ════════════════════════════════════════════════════════════════════
 *
 * مسیرهای `/install/*` و `/update/*` هیچ محدودیتی نداشتند و روی سامانه
 * «در حال بهره‌برداری» هم در دسترس بودند. نصب‌کننده پروژه این کارها را
 * انجام می‌دهد:
 *
 *     • نوشتن و بازنویسی فایل `.env`  (شامل رمز دیتابیس و کلید برنامه)
 *     • ایمپورت فایل SQL و بازنویسی ساختار دیتابیس
 *     • ثبت تنظیمات سیستم و کد خرید
 *
 * یعنی یک فرد بیرونی می‌توانست با مرور آدرس `/install`، پیکربندی سایت
 * را بازنویسی کند یا به‌کل سامانه را از کار بیندازد. این یکی از
 * خطرناک‌ترین نقص‌های ممکن در یک سامانه مستقر است.
 *
 * ════════════════════════════════════════════════════════════════════
 *  معیار «نصب‌شده بودن»
 * ════════════════════════════════════════════════════════════════════
 *
 * نصب‌شده تلقی می‌شود اگر «هر دو» شرط برقرار باشند:
 *
 *     ۱) فایل `.env` وجود دارد و `APP_KEY` آن خالی نیست؛
 *     ۲) جدول `business_settings` در دیتابیس وجود دارد و دست‌کم یک
 *        رکورد دارد (نشانه اجرای موفق نصب).
 *
 * چرا هر دو؟ اگر فقط فایل `.env` بررسی شود، در نصب‌های نیمه‌کاره که
 * `.env` ساخته شده اما دیتابیس هنوز ایمپورت نشده، نصب‌کننده قفل می‌شد
 * و ادامه نصب ممکن نبود. با شرط دوم، نصب نیمه‌کاره اجازه ادامه می‌گیرد.
 *
 * ════════════════════════════════════════════════════════════════════
 *  پاسخ در حالت مسدود
 * ════════════════════════════════════════════════════════════════════
 *
 * پاسخ ۴۰۴ (پیدا نشد) داده می‌شود، نه ۴۰۳. پاسخ ۴۰۳ وجود یک صفحه
 * حساس را تأیید می‌کند؛ ۴۰۴ اطلاعاتی افشا نمی‌کند.
 *
 * برای عملیات به‌روزرسانی برنامه‌ریزی‌شده می‌توان به‌صورت موقت با
 * تنظیم متغیر محیطی زیر در فایل `.env` این قفل را باز کرد:
 *
 *     DRIKANA_ALLOW_INSTALLER=true
 *
 * پس از پایان کار، این متغیر باید حذف شود.
 */
class BlockWhenInstalled
{
    /**
     * عبور می‌دهد اگر سامانه هنوز نصب نشده باشد؛ در غیر این صورت ۴۰۴.
     *
     * @param  \Illuminate\Http\Request $request
     * @param  \Closure                 $next
     * @return mixed
     */
    public function handle($request, Closure $next)
    {
        // راه فرار اضطراری برای به‌روزرسانی برنامه‌ریزی‌شده
        if (config('drikana.installer.allow', false)) {
            return $next($request);
        }

        if ($this->isInstalled()) {
            abort(404);
        }

        return $next($request);
    }

    /**
     * آیا سامانه قبلاً نصب شده است؟
     *
     * تمام خطاها اینجا «نصب‌شده فرض می‌شوند» تا در حالت تردید، مسیر
     * حساس بسته بماند (Fail-safe).
     *
     * @return bool
     */
    protected function isInstalled()
    {
        // شرط ۱ — فایل محیطی و کلید برنامه
        if (!$this->envFileHasAppKey()) {
            return false;
        }

        // شرط ۲ — دیتابیس نصب‌شده
        try {
            if (!Schema::hasTable('business_settings')) {
                return false;
            }

            return DB::table('business_settings')->limit(1)->count() > 0;
        } catch (\Exception $e) {
            // اگر نتوانستیم به دیتابیس وصل شویم، یعنی نصب قطعاً کامل
            // نشده است؛ نصب‌کننده باید بتواند مرحله تنظیم دیتابیس را
            // اجرا کند.
            return false;
        }
    }

    /**
     * بررسی وجود APP_KEY در فایل .env.
     *
     * @return bool
     */
    protected function envFileHasAppKey()
    {
        $path = base_path('.env');

        if (!is_file($path) || !is_readable($path)) {
            return false;
        }

        $contents = file_get_contents($path);

        if ($contents === false) {
            return false;
        }

        return (bool) preg_match('/^\s*APP_KEY\s*=\s*\S+/m', $contents);
    }
}
